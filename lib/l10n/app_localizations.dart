import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

class AppLanguage {
  final String code;
  final String label;
  final String nativeLabel;

  const AppLanguage(this.code, this.label, this.nativeLabel);
}

const List<AppLanguage> appLanguages = [
  AppLanguage('zh', '简体中文', '简体中文'),
  AppLanguage('en', '英语', 'English'),
  AppLanguage('ja', '日语', '日本語'),
  AppLanguage('ko', '韩语', '한국어'),
  AppLanguage('ru', '俄语', 'Русский'),
];

AppLanguage appLanguageByCode(String? code) {
  return appLanguages.firstWhere(
    (item) => item.code == (code ?? 'zh'),
    orElse: () => appLanguages.first,
  );
}

Locale localeForLanguage(String? code) {
  switch (appLanguageByCode(code).code) {
    case 'en':
      return const Locale('en', 'US');
    case 'ja':
      return const Locale('ja', 'JP');
    case 'ko':
      return const Locale('ko', 'KR');
    case 'ru':
      return const Locale('ru', 'RU');
    default:
      return const Locale('zh', 'CN');
  }
}

class AppLocalizations {
  final Locale locale;

  const AppLocalizations(this.locale);

  static const List<Locale> supportedLocales = [
    Locale('zh', 'CN'),
    Locale('en', 'US'),
    Locale('ja', 'JP'),
    Locale('ko', 'KR'),
    Locale('ru', 'RU'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(
          context,
          AppLocalizations,
        ) ??
        const AppLocalizations(Locale('zh', 'CN'));
  }

  String get languageCode {
    if (locale.languageCode == 'zh') return 'zh';
    return appLanguageByCode(locale.languageCode).code;
  }

  String t(String source) {
    if (languageCode == 'zh') return source;
    final table = _translations[languageCode];
    return table?[source] ?? source;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return ['zh', 'en', 'ja', 'ko', 'ru'].contains(locale.languageCode);
  }

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture(AppLocalizations(locale));
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

extension AppLocalizationsX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
  String tr(String source) => l10n.t(source);
}

